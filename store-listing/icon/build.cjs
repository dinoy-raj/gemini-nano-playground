// Builds the Prompt Window app icon from one definition: the adaptive icon vector drawables,
// the legacy launcher bitmaps and the 512 x 512 Play Store icon.
// Usage (from repo root): NODE_PATH=$(npm root -g) node store-listing/icon/build.cjs
const path = require('path');
const fs = require('fs');
const { execFileSync } = require('child_process');
const { chromium } = require('playwright');

const ROOT = path.resolve(__dirname, '../..');
const RES = path.join(ROOT, 'app/src/main/res');
const BACKGROUND = '#F8F9FF';

// ---------------------------------------------------------------- geometry (512 x 512 artwork)
const rrect = (x, y, w, h, r) =>
  `M${x + r},${y}H${x + w - r}A${r},${r} 0 0 1 ${x + w},${y + r}V${y + h - r}A${r},${r} 0 0 1 ${x + w - r},${y + h}` +
  `H${x + r}A${r},${r} 0 0 1 ${x},${y + h - r}V${y + r}A${r},${r} 0 0 1 ${x + r},${y}Z`;

function sparkle(cx, cy, r, k = 0.08) {
  const a = r * k, b = r * 0.46;
  return `M${cx},${cy - r}C${cx + a},${cy - b} ${cx + b},${cy - a} ${cx + r},${cy}` +
    `C${cx + b},${cy + a} ${cx + a},${cy + b} ${cx},${cy + r}` +
    `C${cx - a},${cy + b} ${cx - b},${cy + a} ${cx - r},${cy}` +
    `C${cx - b},${cy - a} ${cx - a},${cy - b} ${cx},${cy - r}Z`;
}

const ICON = {
  window: rrect(84, 150, 344, 240, 60),
  box: [84, 150, 428, 390],
  // back card: moved up 38, then turned 8 degrees about (256, 270)
  back: { rotate: 8, pivot: [256, 270], dy: -38, colors: ['#93C5FD', '#60A5FA'] },
  front: ['#34D399', '#12B76A', '#0E9F6E'],
  glow: { color: '#FDE047', cx: 100, cy: 390, r: 150 },
  topLight: [150, 260],
  chevron: 'M150,228L206,270L150,312',
  spark: sparkle(300, 276, 52),
  // whole artwork scaled about its centre so the back card clears the launcher and Play masks
  fit: { scale: 0.9, pivot: [256, 248], dy: 8 },
};

const stops = (colors) => colors.map((c, i) => [i / (colors.length - 1), c]);
const glowStops = (c) => [[0, c, 0.95], [0.6, c, 0.43], [1, c, 0]];

// ---------------------------------------------------------------- SVG
function svgArt() {
  const [x1, y1, x2, y2] = ICON.box, { back, glow, fit } = ICON;
  const lin = (id, colors) => `<linearGradient id="${id}" x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" gradientUnits="userSpaceOnUse">${stops(colors)
    .map(([o, c]) => `<stop offset="${o}" stop-color="${c}"/>`).join('')}</linearGradient>`;
  return `
  <defs>
    ${lin('back', back.colors)}${lin('front', ICON.front)}
    <radialGradient id="glow" cx="${glow.cx}" cy="${glow.cy}" r="${glow.r}" gradientUnits="userSpaceOnUse">${glowStops(glow.color)
      .map(([o, c, a]) => `<stop offset="${o}" stop-color="${c}" stop-opacity="${a}"/>`).join('')}</radialGradient>
    <linearGradient id="top" x1="0" y1="${ICON.topLight[0]}" x2="0" y2="${ICON.topLight[1]}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.38"/><stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/></linearGradient>
  </defs>
  <g transform="translate(${fit.pivot[0]} ${fit.pivot[1] + fit.dy}) scale(${fit.scale}) translate(${-fit.pivot[0]} ${-fit.pivot[1]})">
    <path d="${ICON.window}" fill="url(#back)" transform="rotate(${back.rotate} ${back.pivot[0]} ${back.pivot[1]}) translate(0 ${back.dy})"/>
    <path d="${ICON.window}" fill="url(#front)"/>
    <path d="${ICON.window}" fill="url(#glow)"/>
    <path d="${ICON.window}" fill="url(#top)"/>
    <path d="${ICON.chevron}" fill="none" stroke="#FFFFFF" stroke-width="30" stroke-linecap="round" stroke-linejoin="round"/>
    <path d="${ICON.spark}" fill="#FFFFFF"/>
  </g>`;
}
const svgDoc = (body, bg) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">${bg ? `<rect width="512" height="512" fill="${bg}"/>` : ''}${body}\n</svg>\n`;

// ---------------------------------------------------------------- Android vector drawables
const argb = (hex, a = 1) => '#' + Math.round(a * 255).toString(16).padStart(2, '0').toUpperCase() + hex.slice(1).toUpperCase();

function vdGradient(attrs, items) {
  return `
        <aapt:attr name="android:fillColor">
          <gradient ${attrs}>${items.map(([o, c]) => `
            <item android:offset="${o}" android:color="${c}" />`).join('')}
          </gradient>
        </aapt:attr>`;
}

function vector(comment, body) {
  const { fit } = ICON;
  // 512 artwork centred in the 108dp adaptive canvas: the visible 72dp maps to 512 units
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by store-listing/icon/build.cjs. ${comment} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="768"
    android:viewportHeight="768">
  <group android:translateX="128" android:translateY="128">
    <group
        android:pivotX="${fit.pivot[0]}" android:pivotY="${fit.pivot[1]}"
        android:scaleX="${fit.scale}" android:scaleY="${fit.scale}"
        android:translateY="${fit.dy}">${body}
    </group>
  </group>
</vector>
`;
}

function foreground() {
  const [x1, y1, x2, y2] = ICON.box, { back, glow } = ICON;
  const linAttrs = `android:type="linear" android:startX="${x1}" android:startY="${y1}" android:endX="${x2}" android:endY="${y2}"`;
  const win = (fill) => `
      <path android:pathData="${ICON.window}">${fill}
      </path>`;
  return vector('Prompt Window icon, colour layer.', `
      <!-- back card -->
      <group android:rotation="${back.rotate}" android:pivotX="${back.pivot[0]}" android:pivotY="${back.pivot[1]}">
        <group android:translateY="${back.dy}">${win(vdGradient(linAttrs, stops(back.colors).map(([o, c]) => [o, argb(c)])))}
        </group>
      </group>
      <!-- front window, glow where it meets the card, top light -->${win(vdGradient(linAttrs, stops(ICON.front).map(([o, c]) => [o, argb(c)])))}${win(
        vdGradient(`android:type="radial" android:centerX="${glow.cx}" android:centerY="${glow.cy}" android:gradientRadius="${glow.r}"`,
          glowStops(glow.color).map(([o, c, a]) => [o, argb(c, a)])))}${win(
        vdGradient(`android:type="linear" android:startX="0" android:startY="${ICON.topLight[0]}" android:endX="0" android:endY="${ICON.topLight[1]}"`,
          [[0, argb('#FFFFFF', 0.38)], [1, argb('#FFFFFF', 0)]]))}
      <!-- prompt chevron and sparkle -->
      <path
          android:pathData="${ICON.chevron}"
          android:strokeColor="#FFFFFFFF"
          android:strokeWidth="30"
          android:strokeLineCap="round"
          android:strokeLineJoin="round" />
      <path android:fillColor="#FFFFFFFF" android:pathData="${ICON.spark}" />`);
}

function monochrome() {
  const { back } = ICON;
  return vector('Prompt Window icon, themed (monochrome) layer.', `
      <group android:rotation="${back.rotate}" android:pivotX="${back.pivot[0]}" android:pivotY="${back.pivot[1]}">
        <group android:translateY="${back.dy}">
          <path android:fillColor="#FF000000" android:fillAlpha="0.35" android:pathData="${ICON.window}" />
        </group>
      </group>
      <path android:fillColor="#FF000000" android:fillAlpha="0.7" android:pathData="${ICON.window}" />
      <path
          android:pathData="${ICON.chevron}"
          android:strokeColor="#FF000000"
          android:strokeWidth="30"
          android:strokeLineCap="round"
          android:strokeLineJoin="round" />
      <path android:fillColor="#FF000000" android:pathData="${ICON.spark}" />`);
}

// ---------------------------------------------------------------- bitmaps
const DENSITIES = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };

(async () => {
  const art = svgArt();
  fs.writeFileSync(path.join(__dirname, 'icon.svg'), svgDoc(art));
  fs.writeFileSync(path.join(RES, 'drawable/ic_launcher_foreground.xml'), foreground());
  fs.writeFileSync(path.join(RES, 'drawable/ic_launcher_monochrome.xml'), monochrome());

  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 512, height: 512 } });
  const shot = async (svg, file) => {
    await page.setContent(`<body style="margin:0">${svg}</body>`);
    await page.screenshot({ path: file, omitBackground: true, clip: { x: 0, y: 0, width: 512, height: 512 } });
  };

  // Play Store: full square, opaque, no rounded corners or shadow (Play applies the mask)
  const play = path.join(ROOT, 'app/src/main/ic_launcher-playstore.png');
  await shot(svgDoc(art, BACKGROUND), play);
  execFileSync('convert', [play, '-alpha', 'off', '-define', 'png:color-type=6', play]);
  fs.copyFileSync(play, path.join(ROOT, 'fastlane/metadata/android/en-US/images/icon.png'));

  // Legacy launcher bitmaps: the visible adaptive area inside a squircle or a circle
  const legacy = (round) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">
    <defs><clipPath id="m">${round ? '<circle cx="256" cy="256" r="244"/>' : '<rect x="12" y="12" width="488" height="488" rx="112"/>'}</clipPath></defs>
    <g clip-path="url(#m)"><rect width="512" height="512" fill="${BACKGROUND}"/>
      ${art}</g></svg>`;
  for (const [name, round] of [['ic_launcher', false], ['ic_launcher_round', true]]) {
    const big = path.join(__dirname, `${name}.png`);
    await shot(legacy(round), big);
    for (const [dpi, px] of Object.entries(DENSITIES)) {
      execFileSync('convert', [big, '-resize', `${px}x${px}`, '-quality', '100', '-define', 'webp:lossless=true',
        path.join(RES, `mipmap-${dpi}/${name}.webp`)]);
    }
    fs.unlinkSync(big);
  }
  await browser.close();
  console.log('icon built');
})();
